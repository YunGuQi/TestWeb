let fbContent = fs.readFileSync(fallbackFile, 'utf8');

for (const [id, text] of Object.entries(cityExpansions)) {
  const shortId = { 85: 'city_ind', 86: 'city_cyb', 87: 'city_wab', 88: 'city_nat', 89: 'city_oce' }[id];
  if (shortId) {
    const regex = new RegExp(`(id:\\s*'${shortId}'[\\s\\S]*?desc:\\s*"(.*?)")`, "g");
    fbContent = fbContent.replace(regex, (match, p1, p2) => {
      return p1.replace(p2, p2 + text.replace(/\n/g, '\\n'));
    });
  }
}
fs.writeFileSync(fallbackFile, fbContent);

