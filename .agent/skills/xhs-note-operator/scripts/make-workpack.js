// ── 素材渲染 ────────────────────────────────────────────────────────────────
const ONELINE = (s) => String(s).replace(/\s*\n\s*/g, ' ').replace(/\s{2,}/g, ' ').trim();
const cut = (s, n) => { const t = String(s).trim(); return t.length <= n ? t : t.slice(0, n) + '…（截断，如需完整原文查数据源）'; };
const arr = (v) => Array.isArray(v) ? v : (v == null || v === '' ? [] : [v]);
// 素材是报告体：`【精神画像】` / `【商务契约式理性表达】：` 这类标头属于报告腔，红线不许进正文，
// 一律在渲染前剥掉（`TS_STRIP`）。**例外**：§3.4 弃用词表里的 `【…】` 是「要被替换掉的东西」本身，原样保留。
const prose = (v) => SD.TS_STRIP(ONELINE(typeof v === 'object' && v !== null ? JSON.stringify(v) : v));
const bullet = (label, v, n) => {
  const items = arr(v).map(prose).filter(Boolean);
  if (!items.length) return '';
  return `- ${label}：${items.map((x) => cut(x, n)).join(' ｜ ')}\n`;
};
// 从 flat 里按候选键取第一个有值的
const pick1 = (flat, keys) => { for (const k of keys) if (flat[k] != null && flat[k] !== '') return flat[k]; return ''; };

// 结果名清单（封面与标题都不得出现结果名，标签位不受限）
const resultNames = picked.map((r) => r.name);

// 单个结果的素材块。budget 为该块自由文本的字符预算（结果之间均分）。
const renderResult = (r, budget) => {
  const f = r.flat, a = SD.accentOf(profile, r.name);
  const per = Math.max(120, Math.floor(budget / 6));
  let s = `### r${r.idx} · ${r.name}\n`;
  s += `- 口音（照这个脾气写，不许换腔）：${cut(a.accent || '（画像口音表缺这一条，开工前先补）', per * 2)}\n`;
  s += `- 允许整活：${a.wild || '✗'}${a.wild && a.wild !== '✗' && a.wild !== '否' ? '（可注入，注入点见 §5）' : '（不许注入）'}\n`;
  s += bullet('金句', pick1(f, ['quote']), per);
  s += bullet('结果描述', pick1(f, ['desc', 'description', 'content']), per * 2);
  const tg = SD.splitTags(pick1(f, ['tags', 'cond.tags']));
  if (tg.length) s += `- 数据源标签（**素材**，不是最终 5 个标签——最终标签自己按 §4.1 排）：${cut(tg.join(' ｜ '), per)}\n`;
  const sch = ['morning', 'afternoon', 'night'].map((k) => f['cond.schedule.' + k] || f['schedule.' + k]).filter(Boolean);
  if (sch.length) s += `- 日程：早上 ${cut(prose(sch[0]), per)} ｜ 下午 ${cut(prose(sch[1] || ''), per)} ｜ 晚上 ${cut(prose(sch[2] || ''), per)}\n`;
  const cure = ['cond.curePrescription.dazePlace', 'cond.curePrescription.soulFood', 'cond.curePrescription.spiritBuddy']
    .map((k) => f[k]).filter(Boolean);
  const cureAlt = pick1(f, ['selfCureGuide', 'antidoteList', 'adviceList', 'careGuide']);
  if (cure.length) s += `- 充电日程：发呆地 ${cut(prose(cure[0]), per)} ｜ 灵魂食物 ${cut(prose(cure[1] || ''), per)} ｜ 搭子 ${cut(prose(cure[2] || ''), per)}\n`;
  else if (cureAlt) s += bullet('回血清单', cureAlt, per * 2);
  // 相克感：只给「为什么相克」。相克城市的市名一律不出现在工作包里——
  // 素材层的素材来自数据源字段，工单 01 明确要求「相克地不点名」。
  const toxReason = pick1(f, ['cond.toxicCity.reason', 'toxicScenario', 'toxicMatch', 'toxicMatchReason']);
  if (toxReason) s += `- 相克感：${cut(prose(toxReason), per * 2)}　**只给「为什么相克」：相克城市的市名一律不出现**（要写反差就写这件具体的事，别写「跟 XX 市合不来」）\n`;
  s += bullet('红线警报', pick1(f, ['redFlag', 'redFlags', 'hiddenCost', 'hiddenCosts', 'vampires', 'hiddenCost.frictionLevel']), per);
  const misc = [];
  ['acquiredTrait', 'attachmentType', 'childhoodMark', 'triggers', 'behavior', 'breakdownScenes',
    'firstMeet.scene', 'firstMeet.visual', 'synergy.matchType', 'loveAdvice.single', 'scenarios', 'danmaku']
    .forEach((k) => { if (f[k] != null && f[k] !== '') misc.push(`${k}：${cut(prose(f[k]), Math.min(per, 160))}`); });
  if (misc.length) s += `- 其它可用素材：${misc.slice(0, 4).join(' ｜ ')}\n`;
  if (r.placeholders.length) s += `- ⚠️ 数据源里还有没替换掉的模板占位符 ${r.placeholders.join(' ')} —— 落笔前先确认它在这条里该填什么，别原样抄进正文。\n`;
  return s;
};

