const fs = require('fs');
const path = require('path');
const SD = require(path.join(__dirname, 'skill-data.js'));

// ── 参数 ────────────────────────────────────────────────────────────────────
const argv = process.argv.slice(2);
const arg = (k, d) => { const i = argv.indexOf(k); return i >= 0 && argv[i + 1] ? argv[i + 1] : d; };
const has = (k) => argv.includes(k);
const TEST = arg('--test');
const OUT = arg('--out');
const SLUG = arg('--slug', TEST || '');
const MAX = Number(arg('--max-chars', '20000'));
const QUIET = has('--quiet');
const RESULTS = arg('--results') ? String(arg('--results')).split(',').map((s) => s.trim()).filter(Boolean) : [];
const PICK = Number(arg('--pick', '0')) || 0;
const SEED_ARG = arg('--seed');
const SEED = SD.resolveSeed(SEED_ARG);

if (!TEST) {
  console.error('用法: node "…/make-workpack.js" --test <测试名> (--pick N [--seed S/auto] | --results r1,r3,…) [--out 路径] [--slug 目录名]');
  console.error('      例: node "…/make-workpack.js" --test 性格城市匹配 --pick 6 --seed auto');
  process.exit(1);
}
if (!PICK && !RESULTS.length) {
  console.error('必须给 --pick N [--seed S/auto]（种子抽样）或 --results r1,r3,…（显式清单）之一 —— 统计口径要可复现。');
  process.exit(1);
}

const root = SD.findRoot(__dirname);

// 参数/数据错误统一走这里：给一句人能读懂的话，不要甩一段栈。
// 交付场景是操盘手在终端里跑，堆栈只会掩盖真正的原因（结果号越界 / 数据源缺文件 / 词表缺项）。
const die = (e) => { console.error(`❌ ${e && e.message ? e.message : e}`); process.exit(1); };
